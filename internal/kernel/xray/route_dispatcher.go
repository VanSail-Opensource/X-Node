var errRouteSniffingTimeout = errors.New("timeout on sniffing")

type routeCachedReader struct {
	sync.Mutex
	reader buf.TimeoutReader // *pipe.Reader or *buf.TimeoutWrapperReader
	cache  buf.MultiBuffer
}

func (r *routeCachedReader) Cache(b *buf.Buffer, deadline time.Duration) error {
	mb, err := r.reader.ReadMultiBufferTimeout(deadline)
	if err != nil {
		return err
	}
	r.Lock()
	if !mb.IsEmpty() {
		r.cache, _ = buf.MergeMulti(r.cache, mb)
	}
	b.Clear()
	rawBytes := b.Extend(min(r.cache.Len(), b.Cap()))
	n := r.cache.Copy(rawBytes)
	b.Resize(0, int32(n))
	r.Unlock()
	return nil
}

func (r *routeCachedReader) readInternal() buf.MultiBuffer {
	r.Lock()
	defer r.Unlock()

	if r.cache != nil && !r.cache.IsEmpty() {
		mb := r.cache
		r.cache = nil
		return mb
	}

	return nil
}

func (r *routeCachedReader) ReadMultiBuffer() (buf.MultiBuffer, error) {
	mb := r.readInternal()
	if mb != nil {
		return mb, nil
	}

	return r.reader.ReadMultiBuffer()
}

func (r *routeCachedReader) ReadMultiBufferTimeout(timeout time.Duration) (buf.MultiBuffer, error) {
	mb := r.readInternal()
	if mb != nil {
		return mb, nil
	}

	return r.reader.ReadMultiBufferTimeout(timeout)
}

func (r *routeCachedReader) Interrupt() {
	r.Lock()
	if r.cache != nil {
		r.cache = buf.ReleaseMulti(r.cache)
	}
	r.Unlock()
	if p, ok := r.reader.(*pipe.Reader); ok {
		p.Interrupt()
	}
}

// routeHandlerPicker resolves a rule and its handler against the same
// publication. A non-nil route with a nil handler must fail closed.
type routeHandlerPicker interface {
	PickRouteAndHandler(routing.Context) (routing.Route, outbound.Handler, error)
}

type routeDispatcher struct {
	ohm    outbound.Manager
	router routing.Router
	picker routeHandlerPicker
	policy policy.Manager
	stats  stats.Manager
	fdns   dns.FakeDNSEngine
}

var dispatcherMessageType = serial.GetMessageType(&appdispatcher.Config{})

func installRouteDispatcher(config *core.Config) {
	for i, app := range config.App {
		if app.Type == dispatcherMessageType {
			config.App[i] = serial.ToTypedMessage(&DispatcherConfig{NativeValue: app.Value})
		}
	}
}

func init() {
	common.Must(common.RegisterConfig((*DispatcherConfig)(nil), func(ctx context.Context, raw any) (any, error) {
		// Keep native config decoding and feature resolution, including FakeDNS.
		var config appdispatcher.Config
		if err := proto.Unmarshal(raw.(*DispatcherConfig).NativeValue, &config); err != nil {
			return nil, err
		}
		d := new(routeDispatcher)
		if err := core.RequireFeatures(ctx, func(om outbound.Manager, router routing.Router, pm policy.Manager, sm stats.Manager, dc dns.Client) error {
			core.OptionalFeatures(ctx, func(fdns dns.FakeDNSEngine) {
				d.fdns = fdns
			})
			d.ohm, d.router, d.policy, d.stats = om, router, pm, sm
			d.picker, _ = router.(routeHandlerPicker)
			return nil
		}); err != nil {
			return nil, err
		}
		return d, nil
	}))
}

